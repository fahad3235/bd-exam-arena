const BN_DIGITS = ['০','১','২','৩','৪','৫','৬','৭','৮','৯'];
function bnDigits(v){
  return String(v).replace(/[0-9]/g, d => BN_DIGITS[+d]);
}
function fmtNum(v, lang){
  if (typeof v === 'number' && !Number.isInteger(v)) v = Math.round(v*100)/100;
  return lang === 'bn' ? bnDigits(v) : String(v);
}
